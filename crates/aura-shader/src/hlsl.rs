//! A geometry program as an HLSL mesh shader.
//!
//! The first code generator of aura-shader. It writes HLSL rather than DXIL
//! bitcode: the DirectX shader compiler then does register allocation,
//! validation and signing, and a wrong translation shows up as readable
//! source. Every SSA value becomes a `uint` holding the register's bits;
//! float operations reinterpret them.
//!
//! How the console's model maps onto a mesh shader:
//!
//! - **One thread per lane.** A 64-lane wave becomes a 64-thread group.
//!   EXEC of the shape "the first n lanes" ([`Mask::LowLanes`]) becomes
//!   `lane < n`; vector writes outside it keep the old value.
//! - **Compare results stay per lane.** A console compare writes a 64-bit
//!   lane mask, but the programs here only read their own lane's bit back
//!   (`v_cndmask`), and a host wave may be 32 lanes wide. Each lane keeps
//!   its own bit instead of a wave-wide mask.
//! - **Scalar memory reads title memory.** GPU addresses are title
//!   addresses, so `s_load`/`s_buffer_load` read a window of title memory
//!   (`title_memory`, based at the address in the wave constants).
//! - **Input vertices** come from the earlier stage's output in the
//!   console's LDS layout (`es_ring`), read at the same byte addresses.
//! - **Output vertices** are the values each EMIT completed ([`GsProgram`]),
//!   one triangle per lane. Which dwords form the clip position is decided
//!   by the console's copy stage, not by this program; until that stage is
//!   read, dwords 0-3 stand in for it.
//!
//! The SGPRs the wave starts with (system values, the engine prefix, root
//! arguments) arrive as a constant block, so the program reads them by
//! number exactly as the console's code does.

use std::collections::{BTreeMap, HashSet};
use std::fmt::Write;

use crate::cfg::Cfg;
use crate::gfx10::{Encoding, Inst};
use crate::gsout::GsProgram;
use crate::lanes::{Lanes, Mask};
use crate::operands::{Unit, UseKind};
use crate::ssa::{Ssa, ValueDef, ValueId};

/// The generated shader and what could not be translated.
#[derive(Debug, Clone)]
pub struct MeshShader {
    pub source: String,
    /// Instructions emitted as zero, with the reason.
    pub unsupported: Vec<(usize, String)>,
}

const PRELUDE: &str = r#"// Generated by aura-shader from a console geometry program.
cbuffer Wave : register(b0)
{
    uint4 sgpr_block[32];  // s0..s127 as the console fills them at wave start
    uint title_base_lo;    // title address of title_memory's first byte
    uint title_base_hi;
};
ByteAddressBuffer title_memory : register(t0);
ByteAddressBuffer es_ring : register(t1);
StructuredBuffer<uint2> gs_lane_inputs : register(t2); // v0, v1 of each lane

uint sgpr(uint n) { return sgpr_block[n >> 2][n & 3]; }
float f(uint x) { return asfloat(x); }
uint title_load(uint lo, uint hi, uint offset) { return title_memory.Load(lo + offset - title_base_lo); }
uint lane_bit(uint lo, uint hi, uint lane) { return lane < 32 ? (lo >> lane) & 1 : (hi >> (lane - 32)) & 1; }
uint mbcnt_lo(uint mask, uint acc, uint lane) { return acc + countbits(lane >= 32 ? mask : mask & ((1u << lane) - 1u)); }
uint mbcnt_hi(uint mask, uint acc, uint lane) { return acc + countbits(lane >= 32 ? mask & ((1u << (lane - 32)) - 1u) : 0u); }
float med3(float a, float b, float c) { return max(min(a, b), min(max(a, b), c)); }
float mul_legacy(float a, float b) { return (a == 0.0 || b == 0.0) ? 0.0 : a * b; }
uint bfe_u(uint x, uint field) { uint o = field & 31, w = (field >> 16) & 0x7f; return w == 0 ? 0 : (w >= 32 ? x >> o : (x >> o) & ((1u << w) - 1u)); }
uint bfe_i(uint x, uint field) { uint o = field & 31, w = (field >> 16) & 0x7f; if (w == 0) return 0; if (w >= 32) return uint(int(x) >> o); return uint((int(x << (32 - o - w))) >> (32 - w)); }
uint2 bfm64(uint count, uint offset) { uint64_t m = ((((uint64_t)1) << (count & 63)) - 1) << (offset & 63); return uint2(uint(m), uint(m >> 32)); }
"#;

struct Gen<'a> {
    cfg: &'a Cfg,
    ssa: &'a Ssa,
    lanes: Lanes<'a>,
    body: String,
    unsupported: Vec<(usize, String)>,
    /// Values holding one lane's compare bit (0 or 1) rather than mask bits.
    lane_bits: HashSet<ValueId>,
}

fn v(id: ValueId) -> String {
    format!("v{id}")
}

impl<'a> Gen<'a> {
    fn use_of(&self, i: usize, u: Unit, kind: UseKind) -> Option<ValueId> {
        self.ssa.uses[i].iter().find(|(x, k, _)| *x == u && *k == kind).map(|e| e.2)
    }

    /// A source operand code as a `uint` expression.
    fn src(&self, i: usize, code: u32) -> String {
        let inst = &self.cfg.insts[i];
        match code {
            0..=124 | 126 | 127 => self.reg(i, Unit::S(code as u8)),
            128..=192 => format!("{}u", code - 128),
            193..=208 => format!("{}u", (-(code as i64 - 192)) as u32),
            240..=248 => {
                let bits: u32 = [
                    0x3f00_0000, 0xbf00_0000, 0x3f80_0000, 0xbf80_0000, 0x4000_0000, 0xc000_0000,
                    0x4080_0000, 0xc080_0000, 0x3e22_f983,
                ][(code - 240) as usize];
                format!("0x{bits:08x}u")
            }
            253 => self.reg(i, Unit::Scc),
            255 => format!("0x{:08x}u", inst.literal().unwrap_or(0)),
            256..=511 => self.reg(i, Unit::V((code - 256) as u8)),
            _ => "0u".into(),
        }
    }

    fn reg(&self, i: usize, u: Unit) -> String {
        self.use_of(i, u, UseKind::Read).map_or_else(|| "0u".into(), v)
    }

    fn def(&self, i: usize, u: Unit) -> Option<ValueId> {
        self.ssa.defs[i].iter().find(|(x, _)| *x == u).map(|e| e.1)
    }

    fn assign(&mut self, i: usize, u: Unit, expr: String) {
        if let Some(d) = self.def(i, u) {
            let _ = writeln!(self.body, "    uint {} = {};", v(d), expr);
        }
    }

    /// A vector write: in the lanes the guard leaves off, the old value.
    fn assign_lane(&mut self, i: usize, u: Unit, expr: String) {
        let Some(d) = self.def(i, u) else { return };
        let guard = self.lanes.guard(i);
        let old = self.use_of(i, u, UseKind::Keep).map_or_else(|| "0u".into(), v);
        let line = match guard {
            None | Some(Mask::All) | Some(Mask::Entry) => format!("    uint {} = {};", v(d), expr),
            Some(Mask::LowLanes(n)) => format!("    uint {} = lane < {} ? {} : {};", v(d), v(n), expr, old),
            Some(other) => {
                self.unsupported.push((i, format!("lane mask {other:?}")));
                format!("    uint {} = {};", v(d), expr)
            }
        };
        let _ = writeln!(self.body, "{line}");
    }

    fn unsupported(&mut self, i: usize, why: String) {
        self.unsupported.push((i, why));
        for (u, _) in self.ssa.defs[i].clone() {
            self.assign(i, u, "0u".into());
        }
    }

    /// Source `k` of a vector instruction as a float, with VOP3 abs/neg.
    fn fsrc(&self, i: usize, codes: &[u32], k: usize) -> String {
        let inst = &self.cfg.insts[i];
        let mut e = format!("f({})", self.src(i, codes[k]));
        if inst.encoding == Encoding::Vop3 {
            if (inst.words[0] >> (8 + k)) & 1 == 1 {
                e = format!("abs({e})");
            }
            if (inst.words[1] >> (29 + k)) & 1 == 1 {
                e = format!("(-{e})");
            }
        }
        e
    }

    fn instruction(&mut self, i: usize) {
        let cfg = self.cfg;
        let inst: &Inst = &cfg.insts[i];
        let name = inst.name().unwrap_or("?").to_string();
        let w0 = inst.words[0];
        match inst.encoding {
            Encoding::Sopp | Encoding::Ds if name.starts_with("ds_write") || inst.encoding == Encoding::Sopp => {}
            Encoding::Sop1 | Encoding::Sop2 | Encoding::Sopc => self.scalar(i, &name, w0),
            Encoding::Smem => self.smem(i, &name),
            Encoding::Ds => self.lds_read(i, &name),
            Encoding::Vop1 | Encoding::Vop2 | Encoding::Vopc | Encoding::Vop3 => self.vector(i, &name),
            _ => self.unsupported(i, format!("{name}: encoding not translated yet")),
        }
    }

    fn scalar(&mut self, i: usize, name: &str, w0: u32) {
        let (a, b) = (self.src(i, w0 & 0xff), self.src(i, (w0 >> 8) & 0xff));
        let sdst = ((w0 >> 16) & 0x7f) as u8;
        let res = |g: &Gen| g.def(i, Unit::S(sdst)).map(v);
        match name {
            "s_mov_b32" => self.assign(i, Unit::S(sdst), a),
            "s_and_b32" | "s_lshl_b32" | "s_bfe_u32" | "s_bfe_i32" | "s_add_i32" | "s_add_u32" | "s_or_b32" => {
                let e = match name {
                    "s_and_b32" => format!("{a} & {b}"),
                    "s_or_b32" => format!("{a} | {b}"),
                    "s_lshl_b32" => format!("{a} << ({b} & 31)"),
                    "s_bfe_u32" => format!("bfe_u({a}, {b})"),
                    "s_bfe_i32" => format!("bfe_i({a}, {b})"),
                    _ => format!("{a} + {b}"),
                };
                self.assign(i, Unit::S(sdst), e);
                let r = res(self).unwrap_or_else(|| "0u".into());
                let scc = match name {
                    "s_add_i32" => format!("((({a}) ^ {r}) & (({b}) ^ {r})) >> 31"),
                    "s_add_u32" => format!("{r} < ({a}) ? 1u : 0u"),
                    _ => format!("{r} != 0 ? 1u : 0u"),
                };
                self.assign(i, Unit::Scc, scc);
            }
            "s_cmp_eq_u32" | "s_cmp_lg_u32" | "s_cmp_gt_u32" | "s_cmp_lt_u32" => {
                let op = match name {
                    "s_cmp_eq_u32" => "==",
                    "s_cmp_lg_u32" => "!=",
                    "s_cmp_gt_u32" => ">",
                    _ => "<",
                };
                self.assign(i, Unit::Scc, format!("({a}) {op} ({b}) ? 1u : 0u"));
            }
            "s_bfm_b64" => {
                let _ = writeln!(self.body, "    uint2 m{i} = bfm64({a}, {b});");
                self.assign(i, Unit::S(sdst), format!("m{i}.x"));
                self.assign(i, Unit::S(sdst + 1), format!("m{i}.y"));
            }
            "s_cselect_b64" => {
                let scc = self.reg(i, Unit::Scc);
                let (s0, s1) = (w0 & 0xff, (w0 >> 8) & 0xff);
                for k in 0..2u32 {
                    let pick = |code: u32| match code {
                        0..=127 => self.reg(i, Unit::S((code + k) as u8)),
                        193 => "0xffffffffu".into(), // -1: both halves set
                        128 => "0u".into(),
                        _ => self.src(i, code),
                    };
                    let e = format!("{scc} != 0 ? {} : {}", pick(s0), pick(s1));
                    self.assign(i, Unit::S(sdst + k as u8), e);
                }
            }
            _ => self.unsupported(i, format!("{name}: scalar op not translated yet")),
        }
    }

    fn smem(&mut self, i: usize, name: &str) {
        let cfg = self.cfg;
        let s = cfg.insts[i].smem().expect("smem");
        let n: u32 = if name.ends_with("x16") { 16 } else if name.ends_with("x8") { 8 } else if name.ends_with("x4") { 4 } else if name.ends_with("x2") { 2 } else { 1 };
        if !(name.starts_with("s_load_dword") || name.starts_with("s_buffer_load_dword")) {
            return self.unsupported(i, format!("{name}: scalar memory op not translated yet"));
        }
        // A buffer load's base address is in its descriptor's first two
        // dwords (48 bits); a plain load's in the SGPR pair.
        let lo = self.reg(i, Unit::S(s.sbase));
        let hi = format!("({} & 0xffffu)", self.reg(i, Unit::S(s.sbase + 1)));
        let offset = if s.soffset == 0x7d {
            format!("{}u", s.offset)
        } else {
            format!("{}u + {}", s.offset, self.src(i, u32::from(s.soffset)))
        };
        for k in 0..n {
            let e = format!("title_load({lo}, {hi}, {offset} + {}u)", 4 * k);
            self.assign(i, Unit::S(s.sdata + k as u8), e);
        }
    }

    fn lds_read(&mut self, i: usize, name: &str) {
        let ds = self.cfg.insts[i].ds().expect("ds");
        let addr = self.reg(i, Unit::V(ds.addr));
        let offsets: Vec<u32> = match name {
            "ds_read2_b32" => vec![u32::from(ds.offset0) * 4, u32::from(ds.offset1) * 4],
            "ds_read_b32" => vec![u32::from(ds.offset16())],
            _ => return self.unsupported(i, format!("{name}: LDS op not translated yet")),
        };
        for (k, off) in offsets.into_iter().enumerate() {
            self.assign_lane(i, Unit::V(ds.vdst + k as u8), format!("es_ring.Load({addr} + {off}u)"));
        }
    }

    fn vector(&mut self, i: usize, name: &str) {
        let cfg = self.cfg;
        let inst = &cfg.insts[i];
        let (w0, w1) = (inst.words[0], inst.words.get(1).copied().unwrap_or(0));
        if name == "v_nop" {
            return;
        }
        // Source codes and destinations as operands.rs reads them.
        let sdwa = inst.encoding != Encoding::Vop3 && w0 & 0x1ff == 0xf9;
        let src0 = match w0 & 0x1ff {
            0xf9 => {
                if (w1 >> 23) & 1 == 1 { w1 & 0xff } else { 256 + (w1 & 0xff) }
            }
            s => s,
        };
        let (codes, vdst, sdst): (Vec<u32>, u32, Option<u32>) = match inst.encoding {
            Encoding::Vop1 => (vec![src0], (w0 >> 17) & 0xff, None),
            Encoding::Vop2 => (vec![src0, 256 + ((w0 >> 9) & 0xff)], (w0 >> 17) & 0xff, None),
            Encoding::Vopc => (vec![src0, 256 + ((w0 >> 9) & 0xff)], 0, Some(106)),
            _ => {
                let c = vec![w1 & 0x1ff, (w1 >> 9) & 0x1ff, (w1 >> 18) & 0x1ff];
                let compare = name.starts_with("v_cmp");
                (c, w0 & 0xff, compare.then_some(w0 & 0xff))
            }
        };
        let s = |k: usize| self.src(i, codes[k]);
        // SDWA operand selects (only the source-1 word/byte select is used here).
        let s1 = if sdwa {
            let sel = (w1 >> 24) & 7;
            match sel {
                0..=3 => format!("(({} >> {}u) & 0xffu)", s(1), 8 * sel),
                4 => format!("({} & 0xffffu)", s(1)),
                5 => format!("({} >> 16)", s(1)),
                _ => s(1),
            }
        } else if codes.len() > 1 {
            s(1)
        } else {
            String::new()
        };
        let fs = |k: usize| self.fsrc(i, &codes, k);
        let out = Unit::V(vdst as u8);
        let float = |e: String| format!("asuint({e})");
        let e = match name {
            "v_mov_b32" => s(0),
            "v_sub_f32" => float(format!("{} - {}", fs(0), fs(1))),
            "v_add_f32" => float(format!("{} + {}", fs(0), fs(1))),
            "v_mul_f32" => float(format!("{} * {}", fs(0), fs(1))),
            "v_mul_legacy_f32" => float(format!("mul_legacy({}, {})", fs(0), fs(1))),
            "v_fma_f32" => float(format!("mad({}, {}, {})", fs(0), fs(1), fs(2))),
            "v_fmac_f32" => {
                let acc = self.use_of(i, out, UseKind::Read).map_or_else(|| "0u".into(), v);
                float(format!("mad({}, {}, f({acc}))", fs(0), fs(1)))
            }
            "v_med3_f32" => float(format!("med3({}, {}, {})", fs(0), fs(1), fs(2))),
            "v_rsq_f32" => float(format!("rsqrt({})", fs(0))),
            "v_rcp_f32" | "v_rcp_iflag_f32" => float(format!("rcp({})", fs(0))),
            "v_cvt_f32_u32" => float(format!("float({})", s(0))),
            "v_lshlrev_b32" => format!("{s1} << ({} & 31)", s(0)),
            "v_lshrrev_b32" => format!("{s1} >> ({} & 31)", s(0)),
            "v_and_b32" => format!("{} & {s1}", s(0)),
            "v_or_b32" => format!("{} | {s1}", s(0)),
            "v_mad_u32_u24" => format!("({} & 0xffffffu) * ({} & 0xffffffu) + {}", s(0), s(1), s(2)),
            "v_mbcnt_lo_u32_b32" => format!("mbcnt_lo({}, {}, lane)", s(0), s(1)),
            "v_mbcnt_hi_u32_b32" => format!("mbcnt_hi({}, {}, lane)", s(0), s(1)),
            "v_cndmask_b32" => {
                // The select mask: VCC for VOP2, source 2 in VOP3.
                let (lo, hi) = if inst.encoding == Encoding::Vop2 {
                    (self.use_of(i, Unit::S(106), UseKind::Read), self.use_of(i, Unit::S(107), UseKind::Read))
                } else {
                    let m = codes[2];
                    (self.use_of(i, Unit::S(m as u8), UseKind::Read), self.use_of(i, Unit::S(m as u8 + 1), UseKind::Read))
                };
                let bit = match (lo, hi) {
                    (Some(l), _) if self.lane_bits.contains(&l) => format!("{} != 0", v(l)),
                    (Some(l), Some(h)) => format!("lane_bit({}, {}, lane) != 0", v(l), v(h)),
                    _ => "false".into(),
                };
                format!("({bit}) ? {} : {}", s(1), s(0))
            }
            n if n.starts_with("v_cmp_") => {
                let (op, ty) = {
                    let parts: Vec<&str> = n.split('_').collect();
                    (parts[2], parts[3])
                };
                let (a, b) = if ty == "f32" { (fs(0), fs(1)) } else { (s(0), s(1)) };
                let cond = match op {
                    "lt" => format!("{a} < {b}"),
                    "gt" => format!("{a} > {b}"),
                    "eq" => format!("{a} == {b}"),
                    "le" => format!("{a} <= {b}"),
                    "ge" => format!("{a} >= {b}"),
                    "ne" | "lg" | "neq" => format!("{a} != {b}"),
                    "nlt" => format!("!({a} < {b})"),
                    "ngt" => format!("!({a} > {b})"),
                    "nle" => format!("!({a} <= {b})"),
                    "nge" => format!("!({a} >= {b})"),
                    _ => return self.unsupported(i, format!("{n}: compare not translated yet")),
                };
                // Each lane keeps its own bit (see the module comment).
                let dst = sdst.expect("compare destination") as u8;
                self.assign(i, Unit::S(dst), format!("({cond}) ? 1u : 0u"));
                if let Some(d) = self.def(i, Unit::S(dst)) {
                    self.lane_bits.insert(d);
                }
                self.assign(i, Unit::S(dst + 1), "0u".into());
                return;
            }
            _ => return self.unsupported(i, format!("{name}: vector op not translated yet")),
        };
        self.assign_lane(i, out, e);
    }
}

/// Translates a straight-line geometry program whose recovered protocol is
/// `gs` into an HLSL mesh shader (one output triangle per lane).
pub fn gs_to_mesh(cfg: &Cfg, ssa: &Ssa, gs: &GsProgram) -> MeshShader {
    let mut g = Gen {
        cfg,
        ssa,
        lanes: Lanes::new(cfg, ssa),
        body: String::new(),
        unsupported: Vec::new(),
        lane_bits: HashSet::new(),
    };
    // Program inputs.
    for (&u, &id) in &ssa.inputs {
        let e = match u {
            Unit::S(n) => format!("sgpr({n}u)"),
            Unit::V(0) => "lane_in.x".into(),
            Unit::V(1) => "lane_in.y".into(),
            _ => "0u".into(),
        };
        let _ = writeln!(g.body, "    uint {} = {};", v(id), e);
    }
    for i in 0..cfg.insts.len() {
        g.instruction(i);
    }
    // The primitive count: the LowLanes guard of the emitting lanes.
    let count = (0..cfg.insts.len()).find_map(|i| match g.lanes.guard(i) {
        Some(Mask::LowLanes(n)) => Some(n),
        _ => None,
    });
    let nv = gs.vertices.len() as u32;
    let attrs = gs.vertex_stride.div_ceil(4);
    let mut src = String::from(PRELUDE);
    let _ = writeln!(src, "\nstruct Vertex\n{{\n    float4 position : SV_Position;");
    for a in 0..attrs {
        let _ = writeln!(src, "    nointerpolation uint4 a{a} : ATTR{a};");
    }
    let _ = writeln!(src, "}};\n");
    let _ = writeln!(
        src,
        "[outputtopology(\"triangle\")]\n[numthreads(64, 1, 1)]\nvoid main(uint lane : SV_GroupThreadID, uint group : SV_GroupID,\n          out vertices Vertex verts[{}], out indices uint3 tris[64])\n{{\n    uint2 lane_in = gs_lane_inputs[group * 64 + lane];",
        64 * nv
    );
    src.push_str(&g.body);
    let prims = count.map_or_else(|| "64u".to_string(), v);
    let _ = writeln!(src, "    uint prims = min({prims}, 64u);");
    let _ = writeln!(src, "    SetMeshOutputCounts(prims * {nv}u, prims);");
    let _ = writeln!(src, "    if (lane < prims)\n    {{");
    for (k, vert) in gs.vertices.iter().enumerate() {
        let dword = |d: u32| vert.get(&d).map_or_else(|| "0u".into(), |&id| v(id));
        let _ = writeln!(src, "        verts[lane * {nv}u + {k}u].position = asfloat(uint4({}, {}, {}, {}));", dword(0), dword(1), dword(2), dword(3));
        for a in 0..attrs {
            let _ = writeln!(src, "        verts[lane * {nv}u + {k}u].a{a} = uint4({}, {}, {}, {});", dword(4 * a), dword(4 * a + 1), dword(4 * a + 2), dword(4 * a + 3));
        }
    }
    // One triangle per lane from the first strip (the shape handled here).
    let strip: BTreeMap<usize, usize> = gs.strips.first().map(|s| s.iter().copied().enumerate().collect()).unwrap_or_default();
    if strip.len() >= 3 {
        let _ = writeln!(src, "        tris[lane] = uint3(lane * {nv}u + {}u, lane * {nv}u + {}u, lane * {nv}u + {}u);", strip[&0], strip[&1], strip[&2]);
    }
    let _ = writeln!(src, "    }}\n}}");
    // Values defined by phis do not occur in straight-line code.
    debug_assert!(ssa.values.iter().all(|d| !matches!(d, ValueDef::Phi { .. })));
    MeshShader { source: src, unsupported: g.unsupported }
}

